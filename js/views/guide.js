// 使い方・採点の考え方
import { h } from '../ui/dom.js';
import { CATEGORIES } from '../analysis/score.js';

export function renderGuide(main) {
  const catDesc = {
    pitch: '1 音ごとに、あなた自身の基準（音感のクセ）から見た半音のマス目にどれだけ正確に乗っているか。曲のキーから外れた音も見ます。',
    stability: 'ロングトーンの揺れ・途中での音程の下がり・音量の揺れ（ビブラートは除外）。',
    tone: '声の芯（倍音と息の雑音の比）と、声の通り（2〜4kHz の響き）。かすれ・こもり・キンキン声を検出します。',
    onset: '歌い出しで下からすくう「しゃくり」の頻度と長さ、音が跳ぶときの移動の速さ・行き過ぎ。',
    dynamics: 'フレーズの中・フレーズ間の強弱のつけ方と、意図しない音量の急変。',
    phrase: 'フレーズの最後で音程が落ちていないか（語尾処理）。',
    vibrato: 'ビブラートの速さ（5〜7 回/秒）・揺れ幅・規則性。かけないことは減点しすぎません。',
    high: '曲の中で高い音を歌うとき、声質・音程・音量が崩れていないか（力みの検出）。',
  };
  main.append(
    h('div.guide.fade-in',
      h('div.card',
        h('h2', 'このアプリについて'),
        h('p', '機種の採点で高得点を取るための「攻略」ではなく、“誰が聞いても上手いと感じる歌”に近づくほど点が上がるように作った採点アプリです。点数はモチベーション用。本当の目的は、結果画面の先生のコメントと練習メニューで歌を上達させることです。'),
        h('p.small.muted', '録音と解析はすべてこの iPhone の中で行われ、歌声がどこかに送信されることはありません。')
      ),
      h('div.card',
        h('h2', '使い方'),
        h('ol',
          h('li', 'イヤホンマイク（EarPods など）を iPhone につなぐ'),
          h('li', '「歌う」タブでマイクチェック。一番大きい声でもメーターが赤にならない位置に'),
          h('li', '伴奏や原曲をイヤホンで流したい場合は「伴奏・原曲」で音源ファイルを選ぶ（任意）'),
          h('li', '録音ボタンを押して歌い、■ で止めると採点'),
          h('li', '結果の「気になった箇所」をタップして自分の声を聞き返し、練習メニューに取り組む'),
          h('li', '同じ曲を何度か歌って、履歴で伸びを確認')
        ),
        h('p.small', 'ホーム画面に追加すると、アプリのように全画面で使えます（Safari の共有ボタン → 「ホーム画面に追加」）。')
      ),
      h('div.card',
        h('h2', '採点の考え方'),
        h('p.small', '伴奏やお手本のメロディは使わず、歌声だけから「聞き心地」に関わる要素を測ります。8 つの項目を、苦手な項目ほど強く効くように合成して総合点にしています（1 つでも耳障りな要素があると、聞き心地は大きく下がるため）。'),
        CATEGORIES.map((c) => h('div.fb-item', h('h3', c.name, h('span.pill', `重み ${c.weight}`)), h('p.small', catDesc[c.id])))
      ),
      h('div.card',
        h('h2', 'うまく測るコツ'),
        h('ul',
          h('li', '静かな場所で。エアコンや換気扇の音も低い方が正確です'),
          h('li', '伴奏はイヤホンから。スピーカーで流すとマイクが伴奏を拾って誤判定します'),
          h('li', '1 コーラス（1 分）以上歌うと評価が安定します'),
          h('li', 'ハモリやコーラスパートではなく、主旋律を歌ってください')
        )
      ),
      h('div.card',
        h('h2', 'わかること・わからないこと'),
        h('p.small', '✓ 音程の正確さ（半音単位の取り違えや、ふらつき・ぶら下がり）、声の安定、しゃくり、語尾、ビブラート、抑揚、高音での力み、声のかすれ・こもり'),
        h('p.small', '✗ リズム（伴奏とのズレ）、歌詞の正しさ、メロディそのものの正しさ（曲のメロディ情報を持っていないため、「キーに合った別の音」を歌っても検出できません）'),
        h('p.small.muted', 'プロ歌手の声だけを抜き出した音源（アカペラ）を「録音済みの音声を採点」で読み込むと、プロとの違いを比較できます。')
      )
    )
  );
  return null;
}
